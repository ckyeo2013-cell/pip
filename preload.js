// Safe bridge between the page (renderer) and the main process.
const { contextBridge, ipcRenderer } = require('electron');

const on = (channel, cb) => ipcRenderer.on(channel, (_e, ...args) => cb(...args));

contextBridge.exposeInMainWorld('pip', {
  getSettings: () => ipcRenderer.invoke('settings:get'),
  saveSettings: (s) => ipcRenderer.invoke('settings:save', s),
  chat: (payload) => ipcRenderer.invoke('chat', payload),
  voiceStatus: () => ipcRenderer.invoke('voice:status'),
  voiceMic: () => ipcRenderer.invoke('voice:mic'),
  transcribe: (audio) => ipcRenderer.invoke('voice:transcribe', audio),
  speak: (text) => ipcRenderer.invoke('voice:speak', text),
  dictate: (text) => ipcRenderer.invoke('voice:dictate', text),
  onVoiceDictate: (cb) => on('voice-dictate', cb),
  onScreenAsk: (cb) => on('screen-ask', cb),
  copyText: (t) => ipcRenderer.send('clipboard:write', t),
  readClipboard: () => ipcRenderer.invoke('clipboard:read'),
  setInteractive: (v) => ipcRenderer.send('interactive', !!v),
  focus: () => ipcRenderer.send('focus'),
  savePos: (x) => ipcRenderer.send('pos:save', x),
  showMenu: () => ipcRenderer.send('menu:show'),
  respondApproval: (id, ok) => ipcRenderer.send('approve:response', { id, ok: ok === true }),
  openKeyPage: (which) => ipcRenderer.send('link:open', which),
  chooseFolder: () => ipcRenderer.invoke('folder:choose'),
  clearFolder: () => ipcRenderer.invoke('folder:clear'),
  addCalendarUrl: (label, url) => ipcRenderer.invoke('cal:addUrl', { label, url }),
  addCalendarFile: () => ipcRenderer.invoke('cal:addFile'),
  removeCalendar: (id) => ipcRenderer.invoke('cal:remove', id),
  listChats: () => ipcRenderer.invoke('chats:list'),
  getChat: (id) => ipcRenderer.invoke('chats:get', id),
  saveChat: (id, messages) => ipcRenderer.invoke('chats:save', id, messages),
  deleteChat: (id) => ipcRenderer.invoke('chats:delete', id),
  stopChat: () => ipcRenderer.invoke('chat:stop'),
  onProgress: (cb) => on('progress', cb),
  onDelta: (cb) => on('chat:delta', cb),
  onApproval: (cb) => on('approve:request', cb),
  onApprovalExpired: (cb) => on('approve:expired', cb),
  onSay: (cb) => on('say', cb),
  onPet: (cb) => on('pet', cb),
  onHidePanel: (cb) => on('panel:hide', cb),
  onCursor: (cb) => on('cursor', cb),
  onSettings: (cb) => on('settings', cb),
  onVoiceHotkey: (cb) => on('voice-hotkey', cb),
  onOpenChat: (cb) => on('open-chat', cb),
  onChatNote: (cb) => on('chat-note', cb),
  onClipHelper: (cb) => on('clip-helper', cb),
  onArea: (cb) => on('area', cb),
  onGame: (cb) => on('game', cb),
  onMood: (cb) => on('mood', cb),
  onStatus: (cb) => on('status', cb),
  chessScreen: (opts) => ipcRenderer.invoke('chess:screen', opts),
  setShape: (rects) => ipcRenderer.send('shape', rects),
  debugLog: (kind, text) => ipcRenderer.send('debug:log', kind, text),
  debugCopy: () => ipcRenderer.invoke('debug:copy'),
  chessTeach: (w) => ipcRenderer.invoke('chess:teach', w),
  chessAuto: (o) => ipcRenderer.invoke('chess:auto', o),
  chessResign: () => ipcRenderer.invoke('chess:resign'),
  chessStop: () => ipcRenderer.send('chess:stop'),
  moodGet: () => ipcRenderer.invoke('mood:get'),
  moodEvent: (kind) => ipcRenderer.send('mood:event', String(kind)),
});
